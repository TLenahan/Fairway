import { z } from 'zod';

import { SessionSummary } from './analytics';
import { AnalysisScope, ClubCategory } from './enums';
import { Environment } from './session';

/* Claude returns THIS shape via structured output; validate the parse with
   AnalysisVerdictSchema. */
export const AnalysisVerdictSchema = z.object({
  headline: z.string(),
  issues: z.array(
    z.object({
      area: z.string(),
      severity: z.enum(['low', 'medium', 'high']),
      evidence: z.string(),
      why: z.string(),
    }),
  ),
  strengths: z.array(z.object({ area: z.string(), evidence: z.string() })),
  drills: z.array(
    z.object({ name: z.string(), goal: z.string(), howMeasured: z.string() }),
  ),
  caveats: z.array(z.string()),
});
export type AnalysisVerdict = z.infer<typeof AnalysisVerdictSchema>;

export const AnalysisRecordSchema = z.object({
  id: z.string(),
  sessionId: z.string(),
  scope: AnalysisScope,
  model: z.string(),
  createdAt: z.number(),
  verdict: AnalysisVerdictSchema,
  narrative: z.string(),
  inputSummary: z.unknown(), // the computed summary sent to Claude (for audit)
});
export type AnalysisRecord = z.infer<typeof AnalysisRecordSchema>;

/** curated, cited reference numbers — NEVER generated by the model */
export const BaselineSchema = z.object({
  category: ClubCategory,
  level: z.string(),
  source: z.object({ citation: z.string(), url: z.string().nullable() }),
  metrics: z.record(z.string(), z.number()),
});
export type Baseline = z.infer<typeof BaselineSchema>;
export interface BaselineSet {
  get(category: z.infer<typeof ClubCategory>, level: string): Baseline | null;
  list(): Baseline[];
}

export interface AnalysisService {
  analyze(
    scope: z.infer<typeof AnalysisScope>,
    input: {
      current: SessionSummary;
      priorSummaries?: SessionSummary[];
      priorAnalyses?: AnalysisRecord[];
      environment: Environment;
    },
    opts: {
      model: string;
      onDelta?: (textChunk: string) => void;
      signal?: AbortSignal;
    },
  ): Promise<{ verdict: AnalysisVerdict; narrative: string }>;
  chat(
    context: { summary: SessionSummary; priorAnalysis?: AnalysisRecord },
    history: { role: 'user' | 'assistant'; content: string }[],
    message: string,
    opts: {
      model: string;
      onDelta?: (t: string) => void;
      signal?: AbortSignal;
    },
  ): Promise<string>;
}
